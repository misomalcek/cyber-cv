#!/usr/bin/env node
/**
 * Build the search index from the site's own content.
 *
 *   node scripts/build-search.mjs
 *
 * Pages only: headings and prose, so a visitor can find "what went wrong" or
 * "93.9%". Research papers and the 3D crystal left this site; they are not
 * indexed here.
 *
 * No library. A few hundred entries scored by substring and field weight is
 * faster than shipping a search engine, and it is honest about what it does.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

/** Section → the page and anchor it lives at. */
const PAGES = [
  { file: 'src/pages/index.astro',              url: '',                    page: 'Overview' },
  { file: 'src/pages/systems.astro',            url: 'systems/',            page: 'Systems' },
  { file: 'src/pages/career.astro',             url: 'career/',             page: 'Career' },
  { file: 'src/pages/work/index.astro',         url: 'work/',               page: 'Public output' },
  { file: 'src/pages/credentials/index.astro',  url: 'credentials/',        page: 'Credentials' },
];

const strip = (s) => s
  .replace(/<[^>]+>/g, ' ')
  .replace(/\{[^{}]*\}/g, ' ')
  .replace(/&nbsp;/g, ' ')
  .replace(/&amp;/g, '&')
  .replace(/\s+/g, ' ')
  .trim();

const entries = [];

for (const { file, url, page } of PAGES) {
  let src;
  try { src = readFileSync(join(root, file), 'utf8'); } catch { continue; }

  // Section headings carry an id we can jump to.
  for (const m of src.matchAll(/id="([a-z-]+)"[\s\S]{0,400}?title="([^"]+)"/g)) {
    entries.push({ t: m[2], u: `${url}#${m[1]}`, p: page, k: 'section', s: '' });
  }

  // Prose: paragraphs long enough to be worth finding.
  for (const m of src.matchAll(/<p[^>]*>([\s\S]{60,600}?)<\/p>/g)) {
    const text = strip(m[1]);
    if (text.length < 60 || text.includes('=>')) continue;
    entries.push({ t: text.slice(0, 90), u: url, p: page, k: 'text', s: text.slice(0, 260) });
  }
}

// De-duplicate on title+url; the same phrase can appear in several passes.
const seen = new Set();
const unique = entries.filter((e) => {
  const key = `${e.t}|${e.u}`;
  if (seen.has(key) || e.t.length < 4) return false;
  seen.add(key);
  return true;
});

const out = `/**
 * Search index, generated by scripts/build-search.mjs from the site's own pages.
 * Do not edit by hand.
 *
 * ${unique.length} entries, captured ${new Date().toISOString().slice(0, 10)}.
 */
export interface SearchEntry {
  /** title */      t: string;
  /** url, relative to base */ u: string;
  /** where it lives */ p: string;
  /** kind */       k: 'section' | 'text' | 'paper' | 'finding' | 'entity';
  /** snippet */    s: string;
}

export const searchIndex: SearchEntry[] = ${JSON.stringify(unique)};
`;

writeFileSync(join(root, 'src/data/search.ts'), out);
const byKind = unique.reduce((a, e) => ({ ...a, [e.k]: (a[e.k] ?? 0) + 1 }), {});
console.log(`✓ search: ${unique.length} entries →`, byKind);
